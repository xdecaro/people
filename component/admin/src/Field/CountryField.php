    protected function getOptions(): array
    {
        $options = parent::getOptions();
        $alpha3 = strtolower((string) $this->element['code']) !== 'alpha2';
        $language = strtolower(Factory::getApplication()->getLanguage()->getTag());
        $italian = str_starts_with($language, 'it-');
        $countries = [];

        foreach (self::COUNTRIES as $code3 => [$code2, $labelIt, $labelEn]) {
            $value = $alpha3 ? $code3 : $code2;
            $label = $italian ? $labelIt : $labelEn;
            $countries[] = HTMLHelper::_('select.option', $value, $label . ' — ' . $value);
        }

        usort($countries, static fn($a, $b): int => strnatcasecmp((string) $a->text, (string) $b->text));

        return array_merge($options, $countries);
    }
